-- 15. Inventory valuation & capital tied up per product category
-- Purpose: Calculates total monetary value of current stock holding per category.
SELECT 
    category_hierarchy,
    SUM(stock_count * cost_price) AS total_stock_valuation
FROM ec_datamart.clean_products_inventory
GROUP BY category_hierarchy
ORDER BY total_stock_valuation DESC;


-- 16. Dead stock inventory audit (Products with zero sales history)
-- Purpose: Highlights catalog items that have never been purchased.
SELECT 
    p.product_name,
    p.category_hierarchy,
    p.stock_count
FROM ec_datamart.clean_products_inventory AS p
LEFT JOIN ec_datamart.clean_orders AS o
    ON p.prod_id = o.product_id
WHERE o.order_id IS NULL;


-- 17. Products ranked by total website traffic engagement vs stock count
-- Purpose: Correlates user browsing interest with available inventory.
SELECT 
    p.product_name,
    COUNT(w.event_id) AS total_events,
    p.stock_count
FROM ec_datamart.clean_products_inventory AS p
JOIN ec_datamart.clean_website_events AS w
    ON p.prod_id = w.new_product_id
GROUP BY p.product_name, p.stock_count
ORDER BY total_events DESC;


-- 18. Shipping fulfillment duration performance by carrier
-- Purpose: Measures carrier delivery speed and fulfillment efficiency.
SELECT 
    carrier,
    AVG(actual_days_to_deliver) AS avg_delivery_days
FROM ec_datamart.clean_shipping_logs
GROUP BY carrier;


-- 19. Shipping status breakdown profile
-- Purpose: Summarizes shipment milestone distributions.
SELECT 
    status_log_clean,
    COUNT(order_ref) AS no_orders
FROM ec_datamart.clean_shipping_logs
GROUP BY status_log_clean;


-- 20. Delayed shipments count and tracking breakdown by carrier
-- Purpose: Identifies logistics bottlenecks and carrier delay frequencies.
SELECT 
    carrier,
    COUNT(order_ref) AS delayed_orders_count
FROM ec_datamart.clean_shipping_logs
WHERE (actual_days_to_deliver - estimated_days_to_deliver) > 0
GROUP BY carrier
ORDER BY delayed_orders_count DESC;


/*
===============================================================================
SECTION 6: WEBSITE TRAFFIC & USER EXPERIENCE (UX)
===============================================================================
*/

-- 21. Traffic source performance breakdown by event volume
-- Purpose: Evaluates marketing channel effectiveness and user acquisition touchpoints.
SELECT 
    traffic_source,
    COUNT(event_id) AS event_id_count
FROM ec_datamart.clean_website_events 
GROUP BY traffic_source
ORDER BY event_id_count DESC;


-- 22. Device type and Operating System (OS) visit breakdown
-- Purpose: Analyzes technical platform preferences of site visitors.
SELECT 
    device_type,
    os,
    COUNT(visitor_id) AS visits
FROM ec_datamart.clean_website_events 
GROUP BY device_type, os
ORDER BY visits DESC;
