-- 13. Finding customer first-purchase acquisition cohorts
-- Purpose: Isolates the initial transaction date for every customer.
WITH cte_cohorts AS (
    SELECT 
        o.customer_id,
        o.order_date,
        DATENAME(MONTH, o.order_date) AS months,
        ROW_NUMBER() OVER (PARTITION BY customer_id ORDER BY order_date ASC) AS rn
    FROM ec_datamart.clean_customers AS c
    LEFT JOIN ec_datamart.clean_orders AS o
        ON c.cust_id = o.customer_id
    WHERE o.order_date IS NOT NULL
)
SELECT 
    customer_id,
    order_date AS acquisition_date,
    months
FROM cte_cohorts
WHERE rn = 1;


-- 14. Calculating retention cohort index (months since first purchase)
-- Purpose: Tracks customer engagement timeline relative to their signup month.
WITH cte_first_order AS (
    SELECT 
        customer_id,
        MIN(order_date) AS first_order_date
    FROM ec_datamart.clean_orders
    WHERE order_date IS NOT NULL
    GROUP BY customer_id
),
cte_cohort_index AS (
    SELECT 
        o.customer_id,
        o.order_date,
        f.first_order_date,
        DATEDIFF(month, f.first_order_date, o.order_date) AS cohort_index
    FROM ec_datamart.clean_orders AS o
    JOIN cte_first_order AS f
        ON o.customer_id = f.customer_id
)
SELECT 
    customer_id,
    first_order_date,
    order_date,
    cohort_index,
    CASE 
        WHEN cohort_index = 0 THEN 'Month 0 (Signup)'
        WHEN cohort_index = 1 THEN 'Month 1'
        WHEN cohort_index = 2 THEN 'Month 2'
        WHEN cohort_index = 3 THEN 'Month 3'
        ELSE 'Month 4+'
    END AS cohort_label
FROM cte_cohort_index;


