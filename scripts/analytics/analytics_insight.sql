/*
===============================================================================
SECTION 1: PRODUCT & CATEGORY PERFORMANCE
===============================================================================
*/

-- 1. Total revenue generated by each product category hierarchy
-- Purpose: Evaluates top-performing product categories to guide merchandising strategy.
SELECT 
    p.category_hierarchy,
    SUM(o.total_amount) AS revenue
FROM ec_datamart.clean_products_inventory AS p
LEFT JOIN ec_datamart.clean_orders AS o
    ON p.prod_id = o.product_id
GROUP BY p.category_hierarchy
ORDER BY revenue DESC;


-- 2. Top 5 highest-grossing products across the catalog
-- Purpose: Identifies high-value inventory items driving maximum revenue.
SELECT TOP 5 
    p.product_name,
    SUM(o.total_amount) AS revenue
FROM ec_datamart.clean_products_inventory AS p
LEFT JOIN ec_datamart.clean_orders AS o
    ON p.prod_id = o.product_id
GROUP BY p.product_name
ORDER BY revenue DESC;


-- 3. Dead stock / Zero-sale products identified for inventory optimization
-- Purpose: Flags items with zero recorded sales to manage holding costs and dead stock.
SELECT 
    p.product_name,
    SUM(o.total_amount) AS revenue
FROM ec_datamart.clean_products_inventory AS p
LEFT JOIN ec_datamart.clean_orders AS o
    ON p.prod_id = o.product_id
GROUP BY p.product_name
HAVING SUM(o.total_amount) IS NULL OR SUM(o.total_amount) = 0
ORDER BY revenue ASC;


