-- 4. Top-selling product per city using window functions (ROW_NUMBER)
-- Purpose: Identifies regional product preferences for localized marketing campaigns.
WITH cte_city AS (
    SELECT 
        c.city,
        p.product_name,
        p.category_hierarchy,
        SUM(o.total_amount) AS revenue
    FROM ec_datamart.clean_products_inventory AS p
    JOIN ec_datamart.clean_orders AS o
        ON p.prod_id = o.product_id
    JOIN ec_datamart.clean_customers AS c
        ON c.cust_id = o.customer_id
    GROUP BY c.city, p.product_name, p.category_hierarchy
),
cte_ranked_city AS (
    SELECT 
        city,
        product_name,
        category_hierarchy,
        revenue,
        ROW_NUMBER() OVER (PARTITION BY city ORDER BY revenue DESC) AS rn
    FROM cte_city
)
SELECT 
    city,
    product_name,
    category_hierarchy,
    revenue
FROM cte_ranked_city
WHERE rn = 1;


-- 5. Top product categories generating revenue specifically among GOLD and PLATINUM tier customers
-- Purpose: Analyzes purchasing preferences of high-value loyalty customers.
WITH cte_loyalty AS (
    SELECT 
        c.loyalty_tier,
        p.category_hierarchy,
        SUM(o.total_amount) AS revenue
    FROM ec_datamart.clean_products_inventory AS p
    JOIN ec_datamart.clean_orders AS o
        ON p.prod_id = o.product_id
    JOIN ec_datamart.clean_customers AS c
        ON c.cust_id = o.customer_id
    GROUP BY c.loyalty_tier, p.category_hierarchy
)
SELECT 
    loyalty_tier,
    category_hierarchy,
    revenue
FROM cte_loyalty
WHERE loyalty_tier IN ('GOLD', 'PLATINUM')
ORDER BY revenue DESC;


