-- 6. Month-over-Month (MoM) revenue growth analysis using LAG window function
-- Purpose: Tracks business growth velocity and month-over-month fluctuations.
WITH cte_month AS (     
    SELECT 
        DATENAME(MONTH, o.order_date) AS months,
        SUM(o.total_amount) AS revenue,
        YEAR(o.order_date) AS order_year,
        MONTH(o.order_date) AS month_num
    FROM ec_datamart.clean_products_inventory AS p
    JOIN ec_datamart.clean_orders AS o
        ON p.prod_id = o.product_id
    GROUP BY MONTH(o.order_date), YEAR(o.order_date), DATENAME(MONTH, o.order_date)
)
SELECT 
    months,
    revenue,
    LAG(revenue, 1) OVER (ORDER BY order_year, month_num) AS previous_revenue,
    (revenue - LAG(revenue, 1) OVER (ORDER BY order_year, month_num)) AS dif_revenue
FROM cte_month;


-- 7. Elapsed time (days) between consecutive customer purchases using LAG
-- Purpose: Measures customer purchase frequency and retention intervals.
WITH cte_customers AS (
    SELECT 
        c.cust_id,
        o.order_date,
        SUM(o.total_amount) AS revenue
    FROM ec_datamart.clean_orders AS o
    RIGHT JOIN ec_datamart.clean_customers AS c
        ON c.cust_id = o.customer_id
    GROUP BY c.cust_id, o.order_date
)
SELECT 
    cust_id,
    order_date,
    LAG(order_date, 1) OVER (PARTITION BY cust_id ORDER BY order_date ASC) AS previous_day,
    DATEDIFF(day, LAG(order_date, 1) OVER (PARTITION BY cust_id ORDER BY order_date ASC), order_date) AS days_btw_orders,
    revenue
FROM cte_customers;


-- 8. Customer Lifetime Value (LTV) segmentation based on total historical spend
-- Purpose: Re-segments customers into computed tier bands based on aggregate spending.
WITH cte_expenditure AS (
    SELECT 
        c.cust_id,
        c.loyalty_tier,
        SUM(o.total_amount) AS total_spend
    FROM ec_datamart.clean_orders AS o
    RIGHT JOIN ec_datamart.clean_customers AS c
        ON c.cust_id = o.customer_id
    GROUP BY c.cust_id, c.loyalty_tier
)
SELECT 
    cust_id,
    total_spend,
    CASE
        WHEN total_spend < 500 THEN 'VIP'
        WHEN total_spend BETWEEN 500 AND 1000 THEN 'GOLD'
        WHEN total_spend BETWEEN 1000 AND 2500 THEN 'STANDARD'
        ELSE 'DIAMOND'
    END AS computed_ltv_tier
FROM cte_expenditure
ORDER BY total_spend DESC;


-- 9. Running total (cumulative revenue) per customer over time
-- Purpose: Visualizes cumulative financial contribution of individual customers.
WITH cte_cumulative AS (
    SELECT 
        c.cust_id,
        YEAR(o.order_date) AS years,
        DATENAME(MONTH, o.order_date) AS months,
        SUM(o.total_amount) AS revenue,
        MONTH(o.order_date) AS month_num
    FROM ec_datamart.clean_customers AS c
    LEFT JOIN ec_datamart.clean_orders AS o
        ON c.cust_id = o.customer_id
    WHERE o.order_date IS NOT NULL
    GROUP BY c.cust_id, DATENAME(MONTH, o.order_date), YEAR(o.order_date), MONTH(o.order_date)
)
SELECT 
    cust_id,
    months,
    SUM(revenue) OVER (
        PARTITION BY cust_id 
        ORDER BY years, month_num 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS cumulative_revenue
FROM cte_cumulative;


-- 10. Three-month moving average revenue per customer
-- Purpose: Smooths out monthly revenue volatility to identify purchasing trends.
WITH cte_avg AS (
    SELECT 
        c.cust_id,
        YEAR(o.order_date) AS years,
        DATENAME(MONTH, o.order_date) AS months,
        SUM(o.total_amount) AS revenue,
        MONTH(o.order_date) AS month_num
    FROM ec_datamart.clean_customers AS c
    LEFT JOIN ec_datamart.clean_orders AS o
        ON c.cust_id = o.customer_id
    WHERE o.order_date IS NOT NULL
    GROUP BY c.cust_id, DATENAME(MONTH, o.order_date), YEAR(o.order_date), MONTH(o.order_date)
)
SELECT 
    cust_id,
    months,
    AVG(revenue) OVER (
        PARTITION BY cust_id 
        ORDER BY years, month_num 
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS moving_avg_revenue
FROM cte_avg;


-- 11. Top spenders ranked by month using RANK window function
-- Purpose: Identifies leading monthly spenders for targeted promotions.
WITH cte_spenders AS (
    SELECT 
        c.cust_id,
        DATENAME(MONTH, o.order_date) AS months,
        SUM(o.total_amount) AS total_expense,
        MONTH(o.order_date) AS month_num,
        YEAR(o.order_date) AS year_num
    FROM ec_datamart.clean_customers AS c
    LEFT JOIN ec_datamart.clean_orders AS o
        ON c.cust_id = o.customer_id
    WHERE o.order_date IS NOT NULL
    GROUP BY c.cust_id, DATENAME(MONTH, o.order_date), YEAR(o.order_date), MONTH(o.order_date)
)
SELECT 
    cust_id,
    months,
    total_expense,
    RANK() OVER (PARTITION BY year_num, month_num ORDER BY total_expense DESC) AS spending_rank
FROM cte_spenders;


-- 12. Customer spending quartiles using NTILE bucket analysis
-- Purpose: Segments customer base into 4 equal tiers based on aggregate order volume.
WITH cte_quartiles AS (
    SELECT 
        o.customer_id,
        SUM(o.total_amount) AS spending
    FROM ec_datamart.clean_customers AS c
    LEFT JOIN ec_datamart.clean_orders AS o
        ON c.cust_id = o.customer_id
    GROUP BY o.customer_id
)
SELECT 
    customer_id,
    spending, 
    NTILE(4) OVER (ORDER BY spending DESC) AS spending_quartile
FROM cte_quartiles;


